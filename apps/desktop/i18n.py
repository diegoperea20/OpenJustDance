def normalize_lang(lang: object) -> str:
    """'en' default; anything else unknown -> 'en'."""
    try:
        s = str(lang or "").strip().lower()
    except Exception:
        return DEFAULT_LANG
    if s.startswith("es"):
        return "es"
    if s.startswith("en"):
        return "en"
    return DEFAULT_LANG


def tr(lang: object, key: str, **kwargs) -> str:
    """Translated string for *lang*/*key* with English fallback."""
    code = normalize_lang(lang)
    table = STRINGS.get(code, {})
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def difficulty_labels(lang: object) -> dict[str, str]:
    code = normalize_lang(lang)
    return {
        "easy": tr(code, "settings.diff_easy"),
        "medium": tr(code, "settings.diff_medium"),
        "hard": tr(code, "settings.diff_hard"),
    }


def count_labels(lang: object) -> dict[int, str]:
    code = normalize_lang(lang)
    return {
        1: tr(code, "pcount.solo"),
        2: tr(code, "pcount.duo"),
        3: tr(code, "pcount.trio"),
        4: tr(code, "pcount.crew"),
    }
